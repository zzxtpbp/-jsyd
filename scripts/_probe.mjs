import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' });
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
p.on('pageerror', (e) => console.log('[ERR]', e.message));
await p.goto('http://127.0.0.1:4176', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(1000);
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: 'domcontentloaded' });
await p.waitForTimeout(1200);
await p.locator('.guide-window button', { hasText: '新增基础闹钟' }).click();
await p.waitForTimeout(800);
console.log('编辑器按钮:', JSON.stringify(await p.locator('.editor-window button').allTextContents()));
const save = p.locator('.editor-window button', { hasText: '保存并开启' }).first();
console.log('保存按钮 count:', await save.count());
await save.click();
await p.waitForTimeout(900);
console.log('引导回来了:', await p.locator('.guide-window').count());
const txt = await p.evaluate(() => document.body.innerText);
console.log('提示:', (txt.match(/请选择未来的响铃时间|闹钟已保存[^\n]*/) || ['（无）'])[0]);
await b.close();
